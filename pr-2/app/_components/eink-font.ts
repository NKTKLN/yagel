const GLYPH_ADVANCE = 6;

export function pixelTextPath(
  text: string,
  x: number,
  y: number,
  scale: number,
) {
  const segments: string[] = [];

  for (const [characterIndex, character] of [...text].entries()) {
    const rows = (glyphs[character] ?? glyphs[" "]).split("/");
    for (const [rowIndex, row] of rows.entries()) {
      for (const [columnIndex, pixel] of [...row].entries()) {
        if (pixel !== "1") continue;
        const left = x + (characterIndex * GLYPH_ADVANCE + columnIndex) * scale;
        const top = y + rowIndex * scale;
        segments.push(`M${left} ${top}h${scale}v${scale}h-${scale}Z`);
      }
    }
  }

  return segments.join("");
}
